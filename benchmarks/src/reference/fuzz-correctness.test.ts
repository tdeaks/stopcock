// One-runtime-path plan: this suite lost its subject. It used to run seeded
// pipelines through three lanes -- the compact engine's generic executor
// (direct buildPlan+interpret, bypassing the plan cache), the real fused
// pipe() engine (which reached that same executor via the cache), and the
// frozen reference emitter -- and required all three to agree, deliberately
// excluding a naive sequential comparator because it disagrees with a fused
// executor on early-exit callback counts BY DESIGN (fusion runs one pass;
// sequential materializes each step).
//
// The compact fusion engine is deleted (buildPlan/interpret no longer
// exist), and `pipe` imported from `@stopcock/fp/fusion` is now the same
// plain sequential function as root `pipe` -- it is no longer "the same
// executor as interpret" reached a second way, it is the opposite: the
// sequential comparator this file's own header just explained is invalid to
// compare against a fused executor. The frozen emitter is still
// deliberately fused-style codegen (see emitter.ts's header), so comparing
// it against sequential `pipe` would fail on every early-exit-shaped
// pipeline for the exact reason already documented above, not because of a
// real bug.
//
// Re-oracling this suite to a valid two-lane (or restructured) comparison
// against sequential semantics is Phase 3's "re-oracle" work, done
// deliberately with pinned-corpus.json regenerated by its own script and
// reviewed as its own change -- not a same-phase repoint here, which is
// exactly the kind of naive repoint a previous phase's ledger already
