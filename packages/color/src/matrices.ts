// Inline 3x3 * vec3 multiply, writing into `out`. No heap allocation.
export const mul3 = (
  m: Float64Array,
  x: number,
  y: number,
  z: number,
  out: Float64Array,
): Float64Array => {
  out[0] = m[0] * x + m[1] * y + m[2] * z
  out[1] = m[3] * x + m[4] * y + m[5] * z
  out[2] = m[6] * x + m[7] * y + m[8] * z
  return out
}
